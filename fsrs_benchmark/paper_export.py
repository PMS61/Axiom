"""Export report tables to paper/data/*.csv and write the headline numbers to paper/FACTS.md.

Why this module: every number in the paper must come from a results file. This reads the
report outputs (metrics.csv, paired.csv, user_wins.csv) written by fsrs_benchmark.report and
writes two kinds of file:
  paper/data/<name>_overall.csv   one row per model: overall metrics
  paper/data/<name>_gaps.csv      one row per model and gap bin
  paper/data/<name>_paired.csv    paired differences with user-cluster bootstrap CIs
  paper/data/<name>_wins.csv      per-user wins on log loss
  paper/FACTS.md                  one section per dataset; every line ends with its source file

Numbers are rounded to 4 decimals. FACTS.md sections are replaced in place, so re-running one
dataset does not touch the other.

Usage: .venv/bin/python -m fsrs_benchmark.paper_export --run_dir results/paper_anki --name anki --out paper/data
"""
import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from fsrs_benchmark import report

DECIMALS = 4
NAMES = ("anki", "duolingo")
# Headline models for the FACTS diff lines, per dataset: (model key, reference key).
# The v1 Bayesian model is "ours" on Anki and "ours_gpu" (its GPU port) on Duolingo.
FACT_DIFFS = {"anki": [("gbdt", "fsrs_opt"), ("ours", "fsrs_opt")],
              "duolingo": [("gbdt", "fsrs_opt"), ("ours_gpu", "fsrs_opt")]}
FACT_CONSTANTS = ["const_global", "const_user", "const_user_smooth"]
# Models compared with the smoothed constant (the floor), per dataset. v3 is the same key on both.
SMOOTH_REF = "const_user_smooth"
FACT_SMOOTH = {"anki": ["ours", "gbdt", "fsrs_opt", "ours_v3"],
               "duolingo": ["ours_gpu", "gbdt", "fsrs_opt", "ours_v3"]}
DATASET_TITLE = {"anki": "Anki", "duolingo": "Duolingo"}
OVERALL_COLUMNS = ["model", "n", "recall", "log_loss", "brier", "auc", "ece", "rmse_bins", "mean_bias"]
GAP_COLUMNS = ["model", "bin", "n", "recall", "log_loss", "brier", "auc", "ece", "mean_bias"]
PAIRED_OUT = ["reference", "model", "metric", "diff", "lo", "hi", "ci_excludes_zero"]
WINS_OUT = ["reference", "model", "users", "users_lower_log_loss", "share"]
METRIC_TEXT = {"log_loss": "log loss", "brier": "Brier", "auc": "AUC", "ece": "ECE"}
FACTS_HEADER = ("# Paper facts\n\n"
                "Every headline number in the paper. Each line ends with the results file it came from.\n"
                "Generated by `fsrs_benchmark/paper_export.py`; do not edit the sections by hand.\n")


def _name(key):
    return report.DISPLAY.get(key) or key


def _round(df, cols):
    out = df.copy()
    for c in cols:
        if c in out.columns and pd.api.types.is_float_dtype(out[c]):
            out[c] = out[c].round(DECIMALS)
    return out


def overall_table(mt):
    sub = mt[mt["scope"] == "overall"][OVERALL_COLUMNS].copy()
    sub.insert(0, "display", sub["model"].map(_name))
    return _round(sub, ["recall", "log_loss", "brier", "auc", "ece", "rmse_bins", "mean_bias"])


def gaps_table(mt):
    sub = mt[mt["scope"] == "gap"][GAP_COLUMNS].copy()
    sub.insert(0, "display", sub["model"].map(_name))
    return _round(sub, ["recall", "log_loss", "brier", "auc", "ece", "mean_bias"])


def paired_table(pt):
    out = pt[["reference", "model", "metric", "diff", "lo", "hi", "ci_excludes_zero"]].copy()
    out.insert(0, "reference_display", out["reference"].map(_name))
    out.insert(1, "model_display", out["model"].map(_name))
    return _round(out, ["diff", "lo", "hi"])


def wins_table(uw):
    out = uw[WINS_OUT].copy()
    out.insert(0, "reference_display", out["reference"].map(_name))
    out.insert(1, "model_display", out["model"].map(_name))
    return _round(out, ["share"])


def _fmt(x):
    return "n/a" if x is None or pd.isna(x) else f"{float(x):.{DECIMALS}f}"


def _row(mt, model, scope="overall"):
    hit = mt[(mt["model"] == model) & (mt["scope"] == scope)]
    if hit.empty:
        raise ValueError(f"metrics.csv has no overall row for {model}")
    return hit.iloc[0]


def facts_section(name, run_dir, mt, pt, uw):
    """Markdown lines for one dataset. Every line ends with its source file."""
    m_src = f"{run_dir}/metrics.csv"
    p_src = f"{run_dir}/paired.csv"
    title = DATASET_TITLE.get(name, name)
    lines = [f"## {title} ({run_dir})", ""]
    n = int(_row(mt, mt["model"].iloc[0])["n"])
    lines.append(f"- Scored events: {n} (source: {m_src})")
    lines += ["", "Overall metrics per model (log loss, Brier, AUC, ECE):", ""]
    for model in mt["model"].drop_duplicates():
        r = _row(mt, model)
        lines.append(f"- {_name(model)}: log loss {_fmt(r['log_loss'])}, Brier {_fmt(r['brier'])}, "
                     f"AUC {_fmt(r['auc'])}, ECE {_fmt(r['ece'])} (source: {m_src})")
    lines += ["", "Constant baselines (floors), log loss:", ""]
    for model in FACT_CONSTANTS:
        lines.append(f"- {_name(model)}: log loss {_fmt(_row(mt, model)['log_loss'])} (source: {m_src})")
    diffs = FACT_DIFFS.get(name)
    if diffs is None:
        raise ValueError(f"no headline diff models defined for {name!r}")
    lines += ["", "Paired differences vs FSRS-6 (optimised), with 95% user-cluster bootstrap CIs:", ""]
    for model, ref in diffs:
        for metric in report.PAIR_METRICS:
            hit = pt[(pt["model"] == model) & (pt["reference"] == ref) & (pt["metric"] == metric)]
            if hit.empty:
                raise ValueError(f"paired.csv has no {model} vs {ref} row for {metric}; FACTS would be incomplete")
            r = hit.iloc[0]
            flag = "CI excludes 0" if bool(r["ci_excludes_zero"]) else "CI includes 0"
            lines.append(f"- {_name(model)} minus {_name(ref)}, {METRIC_TEXT[metric]}: diff {_fmt(r['diff'])}, "
                         f"95% CI [{_fmt(r['lo'])}, {_fmt(r['hi'])}], {flag} (source: {p_src})")
    lines += ["", "Per-user wins on log loss against FSRS-6 (optimised):", ""]
    for model, ref in diffs:
        hit = uw[(uw["model"] == model) & (uw["reference"] == ref)]
        if hit.empty:
            raise ValueError(f"user_wins.csv has no {model} vs {ref} row; FACTS would be incomplete")
        r = hit.iloc[0]
        lines.append(f"- {_name(model)}: lower log loss for {int(r['users_lower_log_loss'])} of "
                     f"{int(r['users'])} users, share {_fmt(r['share'])} "
                     f"(source: {run_dir}/user_wins.csv)")
    smooth_models = FACT_SMOOTH.get(name)
    if smooth_models is None:
        raise ValueError(f"no smoothed-constant models defined for {name!r}")
    lines += ["", f"Paired log-loss differences vs {_name(SMOOTH_REF)}, with 95% user-cluster bootstrap CIs:", ""]
    for model in smooth_models:
        hit = pt[(pt["model"] == model) & (pt["reference"] == SMOOTH_REF) & (pt["metric"] == "log_loss")]
        if hit.empty:
            raise ValueError(f"paired.csv has no {model} vs {SMOOTH_REF} row; FACTS would be incomplete")
        r = hit.iloc[0]
        flag = "CI excludes 0" if bool(r["ci_excludes_zero"]) else "CI includes 0"
        lines.append(f"- {_name(model)} minus {_name(SMOOTH_REF)}, log loss: diff {_fmt(r['diff'])}, "
                     f"95% CI [{_fmt(r['lo'])}, {_fmt(r['hi'])}], {flag} (source: {p_src})")
    lines += ["", f"Per-user wins on log loss against {_name(SMOOTH_REF)}:", ""]
    for model in smooth_models:
        hit = uw[(uw["model"] == model) & (uw["reference"] == SMOOTH_REF)]
        if hit.empty:
            raise ValueError(f"user_wins.csv has no {model} vs {SMOOTH_REF} row; FACTS would be incomplete")
        r = hit.iloc[0]
        lines.append(f"- {_name(model)}: lower log loss for {int(r['users_lower_log_loss'])} of "
                     f"{int(r['users'])} users, share {_fmt(r['share'])} "
                     f"(source: {run_dir}/user_wins.csv)")
    return lines


def _markers(name):
    return f"<!-- facts:{name}:start -->", f"<!-- facts:{name}:end -->"


def update_facts(path, name, section_lines):
    """Insert or replace the section for one dataset, leaving the other sections as they are."""
    path = Path(path)
    text = path.read_text() if path.exists() else FACTS_HEADER
    start, end = _markers(name)
    block = "\n".join([start] + section_lines + [end]) + "\n"
    if start in text and end in text:
        before = text.split(start, 1)[0]
        after = text.split(end, 1)[1]
        new = before + block + after.lstrip("\n")
    else:
        new = text.rstrip("\n") + "\n\n" + block
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(new)


def export(run_dir, name, out_dir):
    if name not in NAMES:
        raise ValueError(f"--name must be one of {NAMES}, got {name!r}")
    run_dir = Path(run_dir)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    mt = pd.read_csv(run_dir / "metrics.csv", keep_default_na=True)
    pt = pd.read_csv(run_dir / "paired.csv", keep_default_na=True)
    uw = pd.read_csv(run_dir / "user_wins.csv", keep_default_na=True)

    overall_table(mt).to_csv(out_dir / f"{name}_overall.csv", index=False)
    gaps_table(mt).to_csv(out_dir / f"{name}_gaps.csv", index=False)
    paired_table(pt).to_csv(out_dir / f"{name}_paired.csv", index=False)
    wins_table(uw).to_csv(out_dir / f"{name}_wins.csv", index=False)

    facts_path = out_dir.parent / "FACTS.md"
    update_facts(facts_path, name, facts_section(name, run_dir.as_posix(), mt, pt, uw))
    return facts_path


def _seed_of(run_dir):
    info = json.loads((Path(run_dir) / "run_info.json").read_text())
    return int(info["args"]["seed"])


def robustness_tables(run_dirs):
    """Per-seed log loss for every model present in all runs, and GBDT minus FSRS-6 (optimised) per seed.

    Returns (table, diffs, seeds). The table has one row per model, with log loss per seed, the mean
    over seeds, min, max and range (max - min). Models missing from any run (for example v1, which
    exists only in the 100-user final run) are left out.
    """
    runs = [Path(d) for d in run_dirs]
    if len(runs) < 2:
        raise ValueError("robustness needs at least two runs")
    seeds = [_seed_of(r) for r in runs]
    if len(set(seeds)) != len(seeds):
        raise ValueError(f"duplicate seeds across runs: {seeds}")
    mts = [pd.read_csv(r / "metrics.csv") for r in runs]
    overall = [set(m.loc[m["scope"] == "overall", "model"]) for m in mts]
    shared = [mdl for mdl in mts[0].loc[mts[0]["scope"] == "overall", "model"].drop_duplicates()
              if all(mdl in names for names in overall)]
    rows = []
    for mdl in shared:
        vals = [float(_row(m, mdl)["log_loss"]) for m in mts]
        row = {"model": mdl, "display": _name(mdl)}
        row.update({f"log_loss_seed{s}": round(v, DECIMALS) for s, v in zip(seeds, vals)})
        row.update({"mean": round(float(np.mean(vals)), DECIMALS), "min": round(min(vals), DECIMALS),
                    "max": round(max(vals), DECIMALS), "range": round(max(vals) - min(vals), DECIMALS)})
        rows.append(row)
    table = pd.DataFrame(rows)
    diff_rows = []
    for run, seed in zip(runs, seeds):
        pt = pd.read_csv(run / "paired.csv")
        hit = pt[(pt["model"] == "gbdt") & (pt["reference"] == "fsrs_opt") & (pt["metric"] == "log_loss")]
        if hit.empty:
            raise ValueError(f"{run}/paired.csv has no gbdt vs fsrs_opt log_loss row")
        r = hit.iloc[0]
        diff_rows.append({"seed": seed, "reference_display": _name("fsrs_opt"), "model_display": _name("gbdt"),
                          "diff": round(float(r["diff"]), DECIMALS), "lo": round(float(r["lo"]), DECIMALS),
                          "hi": round(float(r["hi"]), DECIMALS),
                          "ci_excludes_zero": bool(r["ci_excludes_zero"]), "source": f"{run.as_posix()}/paired.csv"})
    return table, pd.DataFrame(diff_rows), seeds


def robustness_facts(run_dirs, table, diffs, seeds):
    """Markdown lines for the robustness section. Every line ends with its source file."""
    sources = ", ".join(f"{Path(d).as_posix()}/metrics.csv" for d in run_dirs)
    seed_text = ", ".join(str(s) for s in seeds)
    lines = [f"## Anki robustness: seeds {seed_text} (100 users each)", "",
             "Frozen settings, no tuning. Seed 0 is the final run; v1 exists only there and is left out.", "",
             "Log loss per seed, with mean and min-max range over seeds:", ""]
    for _, r in table.iterrows():
        per_seed = ", ".join(f"seed {s} {r[f'log_loss_seed{s}']:.4f}" for s in seeds)
        lines.append(f"- {r['display']}: {per_seed}; mean {r['mean']:.4f}, range {r['range']:.4f} "
                     f"(source: {sources})")
    lines += ["", "GBDT minus FSRS-6 (optimised), log loss, with 95% user-cluster bootstrap CIs:", ""]
    for _, r in diffs.iterrows():
        flag = "CI excludes 0" if bool(r["ci_excludes_zero"]) else "CI includes 0"
        lines.append(f"- seed {int(r['seed'])}: diff {r['diff']:.4f}, 95% CI [{r['lo']:.4f}, {r['hi']:.4f}], "
                     f"{flag} (source: {r['source']})")
    return lines


def export_robustness(run_dirs, name, out_dir):
    """Write <name>.csv (per-seed log loss), <name>_gbdt_diff.csv and the FACTS.md section for <name>."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    table, diffs, seeds = robustness_tables(run_dirs)
    table.to_csv(out_dir / f"{name}.csv", index=False)
    diffs.to_csv(out_dir / f"{name}_gbdt_diff.csv", index=False)
    facts_path = out_dir.parent / "FACTS.md"
    update_facts(facts_path, name, robustness_facts(run_dirs, table, diffs, seeds))
    return facts_path


def main(argv=None):
    parser = argparse.ArgumentParser(description="Export report tables and FACTS.md for the paper.")
    parser.add_argument("--run_dir", default=None, help="a folder written by fsrs_benchmark.report")
    parser.add_argument("--robustness", nargs="+", default=None,
                        help="run folders for a seed-robustness table (use with --name, e.g. anki_seeds)")
    parser.add_argument("--name", required=True,
                        help=f"dataset name ({', '.join(NAMES)}), or a robustness name such as anki_seeds")
    parser.add_argument("--out", default="paper/data", help="output folder; FACTS.md goes in its parent")
    args = parser.parse_args(argv)
    if args.robustness:
        facts = export_robustness(args.robustness, args.name, args.out)
        print(f"wrote {args.name} robustness tables to {args.out} and updated {facts}", flush=True)
        return 0
    if args.run_dir is None:
        parser.error("--run_dir is required unless --robustness is given")
    if args.name not in NAMES:
        parser.error(f"--name must be one of {NAMES} for a single run")
    facts = export(args.run_dir, args.name, args.out)
    print(f"wrote {args.name} tables to {args.out} and updated {facts}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
