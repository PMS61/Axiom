"""Supplementary numbers for the report: the FSRS fallback count, ours vs ours_kappa, reliability bins.

Why this exists: some numbers quoted in docs/EVALUATION.md are not in metrics.csv or run_info.json
(the fsrs_opt fallback count is not recorded when fsrs_opt was reused with --resume, and the
ours vs ours_kappa correlation is computed from predictions). This module recomputes them from
events.parquet and predictions.parquet of one run and writes supplementary.json next to them.

Usage: .venv/bin/python -m fsrs_benchmark.supplementary --run_dir results/full_u100_c1000

Fallback count: recomputed from the rule in fsrs_benchmark/models/fsrs_model.py (fewer than
MIN_INFORMATIVE_TRAIN informative train rows), not taken from a fit. The optimiser-returns-defaults
case is not covered.
"""
import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from fsrs_benchmark.models.fsrs_model import MIN_INFORMATIVE_TRAIN, _informative

GENERATED_BY = ("Generated by python -m fsrs_benchmark.supplementary from events.parquet and "
                "predictions.parquet of this run directory.")


def fallback_summary(events):
    """Users whose informative train count is below MIN_INFORMATIVE_TRAIN (they keep the defaults)."""
    train = events[events["is_train"].astype(bool)]
    counts = {int(u): len(_informative(g)) for u, g in train.groupby("user_id", sort=True)}
    for u in events["user_id"].unique():  # users with no train rows count as zero
        counts.setdefault(int(u), 0)
    fallback = {u: c for u, c in counts.items() if c < MIN_INFORMATIVE_TRAIN}
    others = sorted(c for u, c in counts.items() if c >= MIN_INFORMATIVE_TRAIN)
    return {
        "rule": "py-fsrs Optimizer defaults are kept when a user has fewer than MIN_INFORMATIVE_TRAIN "
                "informative train rows (fsrs_benchmark/models/fsrs_model.py)",
        "threshold": MIN_INFORMATIVE_TRAIN,
        "informative_definition": "train rows that are not first reviews and have elapsed_days >= 1 (_informative)",
        "n_users": len(counts),
        "n_fallback": len(fallback),
        "fallback_users": {str(u): c for u, c in sorted(fallback.items())},
        "median_informative_other_users": float(np.median(others)) if others else None,
        "n_other_users": len(others),
        "note": "Recomputed from the rule, not from the fit. The optimiser-returned-defaults case is not covered.",
    }


def ours_vs_kappa(preds):
    a, b = preds["ours"].to_numpy(float), preds["ours_kappa"].to_numpy(float)
    return {"pearson_r": round(float(np.corrcoef(a, b)[0, 1]), 4),
            "max_abs_diff": round(float(np.max(np.abs(a - b))), 4),
            "n_events": int(len(a))}


def reliability_bins(preds, n_bins=10):
    """Mean predicted and observed recall per bin for ours, bins with at least one event only."""
    p = preds["ours"].to_numpy(float)
    y = preds["y"].to_numpy(float)
    idx = np.minimum((p * n_bins).astype(int), n_bins - 1)
    out = []
    for b in range(n_bins):
        mask = idx == b
        if mask.any():
            out.append({"bin": b, "n": int(mask.sum()),
                        "mean_p": round(float(p[mask].mean()), 3),
                        "mean_y": round(float(y[mask].mean()), 3)})
    return out


def build(run_dir):
    run_dir = Path(run_dir)
    events = pd.read_parquet(run_dir / "events.parquet")
    preds = pd.read_parquet(run_dir / "predictions.parquet")
    return {
        "generated_by": GENERATED_BY,
        "fsrs_opt_fallback": fallback_summary(events),
        "ours_vs_kappa": ours_vs_kappa(preds),
        "ours_reliability_bins": reliability_bins(preds),
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description="Regenerate supplementary.json for a run.")
    parser.add_argument("--run_dir", required=True)
    parser.add_argument("--out", default=None, help="defaults to <run_dir>/supplementary.json")
    args = parser.parse_args(argv)
    out = Path(args.out) if args.out else Path(args.run_dir) / "supplementary.json"
    out.write_text(json.dumps(build(args.run_dir), indent=2) + "\n")
    print(f"wrote {out}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
