"""Write the paper's LaTeX tables from paper/data/*.csv (never typed by hand).

Outputs (booktabs):
  paper/tables/overall.tex  Table 1: overall metrics, both datasets, floors on top
  paper/tables/paired.tex   Table 2: paired log-loss differences with 95% CIs, user-win shares
  paper/tables/seeds.tex    Anki robustness: per-seed log loss and GBDT - FSRS-6 (opt.) per seed

Usage (from the repo root):
  .venv/bin/python paper/scripts/make_tables.py [--data paper/data] [--out paper/tables]
"""
import argparse
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
PAPER = HERE.parent
DATASETS = ("anki", "duolingo")
DECIMALS = 3
MINUS = "$-$"

# One dict for every short name used in the tables. "ours" is the v1 Bayesian model on Anki and
# "ours_gpu" is its GPU port on Duolingo; both map to the same short name.
SHORT = {
    "const_global": "Const. global",
    "const_user": "Const. user",
    "const_user_smooth": "Const. user (sm.)",
    "fsrs_default": "FSRS-6 def.",
    "fsrs_opt": "FSRS-6 opt.",
    "hlr": "HLR",
    "laglogit": "LagLogit",
    "ours": "v1 (MCMC)",
    "ours_gpu": "v1 (MCMC)",
    "ours_v2": "v2 (MAP)",
    "ours_v3": "v3 (MAP)",
    "gbdt": "GBDT",
}
FLOORS = ["const_global", "const_user", "const_user_smooth"]
V1_KEY = {"anki": "ours", "duolingo": "ours_gpu"}
# Rows of Table 1 in order (v1 key is dataset-specific, filled in per dataset).
OVERALL_ORDER = FLOORS + ["fsrs_default", "fsrs_opt", "hlr", "laglogit", "v1", "ours_v2", "ours_v3", "gbdt"]
METRICS = [("log_loss", "lower"), ("brier", "lower"), ("auc", "higher"), ("ece", "lower")]
PAIRED_MODELS = ["v1", "ours_v3", "gbdt", "fsrs_opt"]
SEED_ORDER = ["const_global", "const_user", "fsrs_default", "fsrs_opt", "hlr", "ours_v3", "gbdt"]


def short(key):
    return SHORT[key]


def _key(dataset, row):
    """Map an order-list entry ("v1" is per dataset) to a model key."""
    return V1_KEY[dataset] if row == "v1" else row


def fmt(x):
    return f"{x:.{DECIMALS}f}"


def _cell_text(value, bold=False):
    if value is None:
        return "not run"
    text = fmt(value)
    return f"\\textbf{{{text}}}" if bold else text


def overall_cells(data_dir):
    """Return {dataset: {model_key: {metric: value or None}}} from the *_overall.csv files."""
    out = {}
    for ds in DATASETS:
        df = pd.read_csv(Path(data_dir) / f"{ds}_overall.csv").set_index("model")
        out[ds] = {}
        for row in OVERALL_ORDER:
            key = _key(ds, row)
            if key in df.index:
                out[ds][row] = {m: float(df.loc[key, m]) for m, _ in METRICS}
            else:
                out[ds][row] = None
    return out


def best_non_constant(cells):
    """For each dataset and metric, the best value among non-floor rows that were run."""
    best = {}
    for ds, rows in cells.items():
        for m, direction in METRICS:
            vals = [r[m] for k, r in rows.items() if k not in FLOORS and r is not None]
            best[(ds, m)] = (min(vals) if direction == "lower" else max(vals)) if vals else None
    return best


def overall_tex(data_dir):
    cells = overall_cells(data_dir)
    best = best_non_constant(cells)
    lines = [
        "% Generated by paper/scripts/make_tables.py from paper/data/*_overall.csv. Do not edit.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Overall metrics on Anki and Duolingo. Constants (top three rows) are floors: "
        "Const. global, Const. user, and Const. user (sm.), the per-user constant shrunk towards the global rate. "
        "FSRS-6 def. and opt. are FSRS-6 with default and optimised weights. "
        "v1 (MCMC) is the same Bayesian model on both datasets: the CPU MCMC on Anki and its GPU port on Duolingo. "
        "v2 and v3 are MAP fits. Bold: best non-constant model per column. "
        "Log loss (LL), Brier and ECE: lower is better; AUC: higher is better.}",
        "\\label{tab:overall}",
        "\\small",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{l rrrr rrrr}",
        "\\toprule",
        " & \\multicolumn{4}{c}{Anki} & \\multicolumn{4}{c}{Duolingo} \\\\",
        "\\cmidrule(lr){2-5}\\cmidrule(lr){6-9}",
        "Model & LL & Brier & AUC & ECE & LL & Brier & AUC & ECE \\\\",
        "\\midrule",
    ]
    for row in OVERALL_ORDER:
        label = short(_key("anki", row))
        if row in FLOORS:
            label = f"{label} (floor)"
        cols = []
        for ds in DATASETS:
            r = cells[ds][row]
            for m, _ in METRICS:
                bold = r is not None and row not in FLOORS and r[m] == best[(ds, m)]
                cols.append(_cell_text(None if r is None else r[m], bold))
        lines.append(f"{label} & " + " & ".join(cols) + " \\\\")
        if row == "const_user_smooth":
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    return "\n".join(lines)


def _paired_lookup(pt, model, reference, metric="log_loss"):
    """Row for (model - reference). Falls back to the reverse row with the sign flipped."""
    hit = pt[(pt["model"] == model) & (pt["reference"] == reference) & (pt["metric"] == metric)]
    if len(hit):
        r = hit.iloc[0]
        return float(r["diff"]), float(r["lo"]), float(r["hi"])
    rev = pt[(pt["model"] == reference) & (pt["reference"] == model) & (pt["metric"] == metric)]
    if len(rev):
        r = rev.iloc[0]
        return -float(r["diff"]), -float(r["hi"]), -float(r["lo"])
    return None


def _win_share(wins, model, reference):
    hit = wins[(wins["model"] == model) & (wins["reference"] == reference)]
    if len(hit):
        return float(hit.iloc[0]["share"])
    rev = wins[(wins["model"] == reference) & (wins["reference"] == model)]
    if len(rev):
        return 1.0 - float(rev.iloc[0]["share"])
    return None


def _signed(x, decimals=DECIMALS):
    return (MINUS if x < 0 else "+") + f"{abs(x):.{decimals}f}"


def _diff_cell(res, decimals=DECIMALS):
    if res is None:
        return "--"
    d, lo, hi = res
    return f"{_signed(d, decimals)} [{_signed(lo, decimals)}, {_signed(hi, decimals)}]"


def paired_tex(data_dir):
    data_dir = Path(data_dir)
    pt = {ds: pd.read_csv(data_dir / f"{ds}_paired.csv") for ds in DATASETS}
    wins = {ds: pd.read_csv(data_dir / f"{ds}_wins.csv") for ds in DATASETS}
    lines = [
        "% Generated by paper/scripts/make_tables.py from paper/data/*_paired.csv and *_wins.csv. Do not edit.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Paired log-loss differences (model minus reference; negative favours the model) with 95\\% "
        "user-clustered bootstrap CIs, and the share of users whose log loss is lower for the model than for "
        "FSRS-6 (opt.). Reference: FSRS-6 (opt.) and the smoothed per-user constant.}",
        "\\label{tab:paired}",
        "\\small",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{l ccc ccc}",
        "\\toprule",
        " & \\multicolumn{3}{c}{Anki} & \\multicolumn{3}{c}{Duolingo} \\\\",
        "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}",
        "Model & vs FSRS-6 opt. & vs const. sm. & user win & vs FSRS-6 opt. & vs const. sm. & user win \\\\",
        "\\midrule",
    ]
    for row in PAIRED_MODELS:
        label = short(_key("anki", row))
        cols = []
        for ds in DATASETS:
            key = _key(ds, row)
            # Duolingo differences are small, so they get 4 decimals; Anki keeps 3.
            dec = 4 if ds == "duolingo" else DECIMALS
            cols.append(_diff_cell(None if key == "fsrs_opt" else _paired_lookup(pt[ds], key, "fsrs_opt"), dec))
            cols.append(_diff_cell(_paired_lookup(pt[ds], key, "const_user_smooth"), dec))
            share = None if key == "fsrs_opt" else _win_share(wins[ds], key, "fsrs_opt")
            cols.append("--" if share is None else f"{100 * share:.0f}\\%")
        lines.append(f"{label} & " + " & ".join(cols) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}}", "\\end{table*}", ""]
    return "\n".join(lines)


def seeds_tex(data_dir):
    df = pd.read_csv(Path(data_dir) / "anki_seeds.csv").set_index("model")
    diff = pd.read_csv(Path(data_dir) / "anki_seeds_gbdt_diff.csv")
    lines = [
        "% Generated by paper/scripts/make_tables.py from paper/data/anki_seeds*.csv. Do not edit.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Anki robustness: log loss on three 100-user samples (seeds 0, 1, 2). "
        "Lower is better. The last row gives the per-seed difference GBDT minus FSRS-6 (opt.) with its 95\\% CI; "
        "its Mean column is the mean of the three per-seed differences. "
        "v1 was not run on seeds 1 and 2, and v2 is not in this table.}",
        "\\label{tab:seeds}",
        "\\small",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{l rrr r}",
        "\\toprule",
        "Model & Seed 0 & Seed 1 & Seed 2 & Mean \\\\",
        "\\midrule",
    ]
    for key in SEED_ORDER:
        r = df.loc[key]
        vals = [float(r[f"log_loss_seed{s}"]) for s in (0, 1, 2)]
        mean = sum(vals) / 3
        lines.append(f"{short(key)} & " + " & ".join(fmt(v) for v in vals) + f" & {fmt(mean)} \\\\")
    lines.append("\\midrule")
    cells = []
    for s in (0, 1, 2):
        d = diff[diff["seed"] == s].iloc[0]
        cells.append(f"{_signed(float(d['diff']))} [{_signed(float(d['lo']))}, {_signed(float(d['hi']))}]")
    mean_diff = float(diff["diff"].mean())
    lines.append("GBDT $-$ FSRS-6 opt. & " + " & ".join(cells) + f" & {_signed(mean_diff)} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    return "\n".join(lines)


def write_all(data_dir, out_dir):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    outputs = {"overall.tex": overall_tex(data_dir), "paired.tex": paired_tex(data_dir),
               "seeds.tex": seeds_tex(data_dir)}
    for name, text in outputs.items():
        (out_dir / name).write_text(text)
    return outputs


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", default=str(PAPER / "data"))
    ap.add_argument("--out", default=str(PAPER / "tables"))
    args = ap.parse_args(argv)
    write_all(args.data, args.out)
    print(f"wrote tables to {args.out}")


if __name__ == "__main__":
    main()
